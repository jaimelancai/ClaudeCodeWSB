#!/bin/bash
# ClaudeCodeWSB - WSL-side uninstaller
#
# Restores the state of /etc/samba/smb.conf and /etc/wsl.conf from backups,
# stops Samba, removes the Samba user, and optionally uninstalls packages.
#
# Works after a COMPLETE install (full state file) and after a FAILED/PARTIAL
# install (in-progress state file, or no state file at all — best-effort mode).
#
# Usage:
#   ./uninstall.sh

set -euo pipefail

readonly STATE_FILE="$HOME/.claudecodewsb-install-state"

# Colors
if [ -t 1 ]; then
    C_RED="$(tput setaf 1)"
    C_GREEN="$(tput setaf 2)"
    C_YELLOW="$(tput setaf 3)"
    C_BLUE="$(tput setaf 4)"
    C_BOLD="$(tput bold)"
    C_RESET="$(tput sgr0)"
else
    C_RED=""; C_GREEN=""; C_YELLOW=""; C_BLUE=""; C_BOLD=""; C_RESET=""
fi

info()    { echo "${C_BLUE}==>${C_RESET} $*"; }
ok()      { echo "${C_GREEN}✓${C_RESET} $*"; }
warn()    { echo "${C_YELLOW}!${C_RESET} $*"; }
err()     { echo "${C_RED}✗${C_RESET} $*" >&2; }
header()  { echo; echo "${C_BOLD}$*${C_RESET}"; echo "${C_BOLD}$(printf '%*s' "${#1}" '' | tr ' ' '=')${C_RESET}"; }

check_not_root() {
    if [ "$EUID" -eq 0 ]; then
        err "Don't run this as root. Run as your normal user; sudo will be used as needed."
        exit 1
    fi
}

confirm() {
    local question="$1"
    local default="${2:-N}"
    local prompt="[y/N]"
    if [ "$default" = "Y" ]; then
        prompt="[Y/n]"
    fi
    read -p "$question $prompt " answer
    answer="${answer:-$default}"
    case "$answer" in
        [Yy]*) return 0 ;;
        *)     return 1 ;;
    esac
}

restore_backup() {
    local path="$1"
    if [ -z "${BACKUP_DIR:-}" ] || [ ! -d "$BACKUP_DIR" ]; then
        # No backups available — best-effort: remove the file only if it's ours
        if [ -e "$path" ] && grep -q "ClaudeCodeWSB" "$path" 2>/dev/null; then
            sudo rm -f "$path"
            ok "Removed $path (generated by ClaudeCodeWSB, no backup to restore)"
        elif [ -e "$path" ]; then
            warn "Leaving $path alone — it wasn't generated by ClaudeCodeWSB."
        fi
        return 0
    fi

    local backup_file
    backup_file="$BACKUP_DIR$(echo "$path" | tr '/' '_')"

    if [ -e "$backup_file" ]; then
        sudo cp -a "$backup_file" "$path"
        ok "Restored $path from backup"
    else
        # No backup means there was no existing file when we installed —
        # remove what we created, but only if it's identifiably ours
        if [ -e "$path" ]; then
            if grep -q "ClaudeCodeWSB" "$path" 2>/dev/null; then
                sudo rm -f "$path"
                ok "Removed $path (no original to restore)"
            else
                warn "Leaving $path alone — it doesn't look like ours."
            fi
        fi
    fi
}

main() {
    header "ClaudeCodeWSB - WSL-side uninstaller"

    check_not_root

    local BEST_EFFORT=false

    if [ -f "$STATE_FILE" ]; then
        # shellcheck disable=SC1090
        . "$STATE_FILE"

        info "Loaded install state."
        echo "  Installed:        ${INSTALL_DATE:-unknown}"
        echo "  Status:           ${INSTALL_STATUS:-unknown}"
        echo "  Backups:          ${BACKUP_DIR:-none}"
        echo "  Samba user:       ${USERNAME:-unknown}"
        echo "  Workspace:        ${WORKSPACE_PATH:-unknown}"
        echo "  Share name:       ${SHARE_NAME:-unknown}"
        echo
        if [ "${INSTALL_STATUS:-}" = "in_progress" ]; then
            warn "This was a PARTIAL/FAILED install. Cleanup will undo only what was done."
            echo
        fi
    else
        warn "No install state found at $STATE_FILE"
        warn "Either ClaudeCodeWSB was never installed, the install failed very early,"
        warn "or the state file was removed."
        echo
        if confirm "Attempt best-effort cleanup anyway?" "N"; then
            BEST_EFFORT=true
            USERNAME=$(whoami)
            BACKUP_DIR=""
            WORKSPACE_PATH=""
            SHARE_NAME=""
            INSTALLED_PACKAGES="samba,samba-common-bin,bubblewrap,socat,nodejs"
            warn "Running in best-effort mode. Each step checks before acting."
            echo
        else
            exit 1
        fi
    fi

    if ! confirm "Proceed with uninstall?"; then
        info "Aborted."
        exit 0
    fi

    info "Verifying sudo access..."
    sudo -v

    # Stop Samba (harmless if not running)
    header "Stopping Samba"
    sudo service smbd stop 2>/dev/null || true
    sudo service nmbd stop 2>/dev/null || true
    ok "Samba stopped (if it was running)."

    # Remove Samba user (check existence first)
    header "Removing Samba user"
    if sudo pdbedit -L 2>/dev/null | grep -q "^$USERNAME:"; then
        sudo smbpasswd -x "$USERNAME"
        ok "Samba user '$USERNAME' removed."
    else
        info "Samba user '$USERNAME' not present; skipping."
    fi

    # Restore configs (handles missing backups gracefully)
    header "Restoring configurations"
    restore_backup /etc/samba/smb.conf
    restore_backup /etc/wsl.conf

    # Workspace handling
    if [ -n "${WORKSPACE_PATH:-}" ] && [ -d "$WORKSPACE_PATH" ]; then
        header "Workspace directory"
        warn "Your workspace at $WORKSPACE_PATH still exists."
        warn "${C_BOLD}This script will NOT delete it — your projects are safe.${C_RESET}"
        echo "If you want to remove it manually: rm -rf '$WORKSPACE_PATH'"
    fi

    # Optional: package removal
    header "System packages"
    echo "The following packages were installed by ClaudeCodeWSB:"
    echo "  ${INSTALLED_PACKAGES:-unknown}"
    echo
    echo "These may also be used by other things on your system."
    if confirm "Remove these packages now?" "N"; then
        # shellcheck disable=SC2086
        sudo apt-get remove -y $(echo "${INSTALLED_PACKAGES:-}" | tr ',' ' ')
        sudo apt-get autoremove -y
        ok "Packages removed."
    else
        info "Packages left in place."
    fi

    # Optional: npm globals
    header "Claude Code (npm global)"
    export PATH="$HOME/.npm-global/bin:$PATH"
    if command -v claude >/dev/null 2>&1; then
        if confirm "Uninstall Claude Code (npm global)?" "N"; then
            npm uninstall -g @anthropic-ai/claude-code
            ok "Claude Code uninstalled."

            if confirm "Remove ~/.claude config directory (auth tokens, settings)?" "N"; then
                rm -rf "$HOME/.claude"
                ok "Removed ~/.claude"
            fi
        else
            info "Claude Code left in place."
        fi
    else
        info "Claude Code not found; skipping."
    fi

    # PATH cleanup in .bashrc
    header "Cleaning up .bashrc"
    if grep -q "# Added by ClaudeCodeWSB installer" "$HOME/.bashrc" 2>/dev/null; then
        sed -i '/# Added by ClaudeCodeWSB installer/,+1d' "$HOME/.bashrc"
        ok "Removed PATH entry from ~/.bashrc"
    else
        info "No .bashrc entry found; skipping."
    fi

    # State file
    if [ -f "$STATE_FILE" ]; then
        rm -f "$STATE_FILE"
        ok "Removed install state file."
    fi

    # Backups
    if [ -n "${BACKUP_DIR:-}" ] && [ -d "$BACKUP_DIR" ]; then
        header "Backups"
        info "Original configs are preserved at: $BACKUP_DIR"
        info "Remove them manually if you no longer need them."
    fi

    header "Uninstall complete"
    echo
    info "You may want to run 'wsl --shutdown' from PowerShell so the next WSL"
    info "start picks up the restored /etc/wsl.conf."
    echo
}

main "$@"
